let weather = "rainy";

switch (weather) {
    case "sunny":
        console.log("Wear light clothes and apply sunscreen.");
        break;

    case "rainy":
        console.log("Wear a waterproof raincoat.");
        break;

    case "winter":
        console.log("Wear warm clothes to protect yourself from cold weather.");
        break;

    case "snowy":
        console.log("Wear a jacket.");
        break;

    default:
        console.log("Invalid weather!");
}